// Pre-compiles dashboard JSX into a single JS bundle so the browser doesn't
// need Babel-in-the-browser (which CSP `unsafe-eval` blocks on Railway).
//
// Run:  node build-dashboard.mjs
// Output: public/dash-assets/dashboard.bundle.js
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const ENTRIES_IN_ORDER = [
  'public/dash-assets/src/lib.jsx',
  'public/dash-assets/src/icons.jsx',
  'public/dash-assets/src/widgets.jsx',
  'public/dash-assets/src/screens-1.jsx',
  'public/dash-assets/src/screens-2.jsx',
  'public/dash-assets/src/screens-3.jsx',
  'public/dash-assets/src/shell.jsx',
  'public/dash-assets/tweaks-panel.jsx',
  'public/dash-assets/src/app.jsx',
];

const OUT = 'public/dash-assets/dashboard.bundle.js';

// Each file was originally a separate `<script type="text/babel">`. The browser
// would give each its own script-scope, so duplicate declarations like
// `const { useState, useEffect, ... } = React;` at the top of every file were
// fine. Once we concatenate them into a single .js file, those become
// duplicate top-level `const` declarations → SyntaxError.
//
// Strip those duplicate React-hook destructurings from each file and emit ONE
// shared destructuring at the top of the bundle. Components still reference
// each other directly via the shared bundle scope (not via window).
const compiled = [];
const REACT_DESTRUCTURE = /^\s*const\s*\{[^}]*\}\s*=\s*React\s*;?\s*$/gm;
// `const __D = () => (window.__DASH_DATA || {});` appears at the top of every
// screens-*.jsx file and would clash when concatenated. Strip from each file
// — we add one declaration to the shared header below.
const DASH_DATA_HELPER = /^\s*const\s+__D\s*=\s*\(\s*\)\s*=>\s*\([^;]*\)\s*;?\s*$/gm;

for (const entry of ENTRIES_IN_ORDER) {
  let src = readFileSync(entry, 'utf8');
  src = src.replace(REACT_DESTRUCTURE, '');
  src = src.replace(DASH_DATA_HELPER, '');

  const result = await build({
    stdin: {
      contents: src,
      loader: 'jsx',
      sourcefile: entry,
      resolveDir: dirname(entry),
    },
    write: false,
    bundle: false,
    target: ['es2019'],
    jsx: 'transform',
    jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment',
    minify: false,
    logLevel: 'error',
  });
  const code = result.outputFiles[0].text;
  compiled.push('/* ===== ' + entry + ' ===== */\n' + code);
}

const sharedHeader =
  `const { useState, useEffect, useRef, useMemo, useCallback, useLayoutEffect, createContext, useContext, Fragment } = React;\n` +
  `const __D = () => (window.__DASH_DATA || {});\n`;
const banner = '/* hamdix dashboard bundle — generated by build-dashboard.mjs */\n';
const bundle = banner + sharedHeader + compiled.join('\n');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, bundle);
console.log(`✓ wrote ${OUT}  (${(bundle.length / 1024).toFixed(1)} kB)`);
